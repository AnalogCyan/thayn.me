// Cuts Remix Icon down to the icons the site uses. Run `npm run icons` after
// adding or removing one; test/icons.test.js fails until you do.

import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src");
const REMIX = path.join(ROOT, "node_modules", "remixicon");
export const ICONS_CSS = path.join(SRC, "styles", "icons.css");
export const ICONS_FONT = path.join(SRC, "static", "fonts", "remixicon.woff2");
const LICENSE_OUT = path.join(SRC, "static", "fonts", "LICENSE-remixicon.txt");

// Every ri-* class a page, template, post or script under src/ names. All of
// them are written out in full, none are assembled at runtime.
export async function usedIcons() {
  const names = new Set();
  const entries = await fs.readdir(SRC, {
    recursive: true,
    withFileTypes: true,
  });
  for (const entry of entries) {
    if (!entry.isFile() || !/\.(html|js|md)$/.test(entry.name)) continue;
    const text = await fs.readFile(
      path.join(entry.parentPath, entry.name),
      "utf8"
    );
    for (const [name] of text.matchAll(/\bri-[a-z0-9-]+/g)) names.add(name);
  }
  return [...names].sort();
}

export function fontHash(bytes) {
  return crypto.createHash("sha1").update(bytes).digest("hex").slice(0, 8);
}

async function main() {
  const { default: subsetFont } = await import("subset-font");
  const { version } = JSON.parse(
    await fs.readFile(path.join(REMIX, "package.json"), "utf8")
  );
  const sourceCss = await fs.readFile(
    path.join(REMIX, "fonts", "remixicon.css"),
    "utf8"
  );
  const codepoints = new Map(
    [
      ...sourceCss.matchAll(
        /\.(ri-[a-z0-9-]+):before\s*{\s*content:\s*"\\([0-9a-f]+)"/g
      ),
    ].map(([, name, hex]) => [name, parseInt(hex, 16)])
  );

  const icons = await usedIcons();
  const unknown = icons.filter((name) => !codepoints.has(name));
  if (unknown.length > 0) {
    throw new Error(`Not in Remix Icon ${version}: ${unknown.join(", ")}`);
  }

  const font = await subsetFont(
    await fs.readFile(path.join(REMIX, "fonts", "remixicon.ttf")),
    String.fromCodePoint(...icons.map((name) => codepoints.get(name))),
    { targetFormat: "woff2" }
  );

  const rules = icons.map(
    (name) =>
      `.${name}:before {\n  content: "\\${codepoints.get(name).toString(16)}";\n}\n`
  );
  const css = `/* Generated by \`npm run icons\` from Remix Icon ${version}, do not edit.
   Remix Icon is Apache-2.0 (/fonts/LICENSE-remixicon.txt); this font is a
   subset of it holding only the icons the site uses. */

@font-face {
  font-family: "remixicon";
  src: url("/fonts/remixicon.woff2?v=${fontHash(font)}") format("woff2");
  font-display: swap;
}

[class^="ri-"],
[class*=" ri-"] {
  font-family: "remixicon" !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules.join("\n")}`;

  await fs.mkdir(path.dirname(ICONS_FONT), { recursive: true });
  await fs.writeFile(ICONS_FONT, font);
  await fs.writeFile(ICONS_CSS, css);
  await fs.copyFile(path.join(REMIX, "License"), LICENSE_OUT);
  console.log(`${icons.length} icons, ${font.length} bytes`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
